export function getSubServices(service: Service): SubService[] {
  const sources = images[service.slug];
  if (!sources || sources.length !== service.offerings.length)
    throw new Error(`Missing sub-service imagery for ${service.slug}`);
  return service.offerings.map((name, index) => ({
    id: `${service.slug}-${index + 1}`,
    name,
    image: `/images/editorial/${sources[index]}.webp`,
    alt: `${descriptions[sources[index]]}. AI editorial reference for ${name}.`,
  }));
}
